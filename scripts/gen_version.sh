#!/bin/bash
# Single generator for blinky-things/types/Version.h (#213).
#
# Usage: scripts/gen_version.sh <build-number>
#
# Called by scripts/build.sh (after it bumps BUILD_NUMBER) and by the
# Makefile `version` target, so every build path embeds the same fields,
# including the git SHA. A plain `b162` with no SHA once hid which code was
# really on a device (2026-05-14, cart-inner).
set -euo pipefail

# Outside a git checkout there is no SHA to embed; say so and still write
# Version.h relative to this script (repo layout is fixed).
if TOP=$(git rev-parse --show-toplevel 2>/dev/null); then
    cd "$TOP"
    IN_GIT=true
else
    cd "$(dirname "$0")/.."
    IN_GIT=false
fi

BUILD="${1:-}"
if ! [[ "$BUILD" =~ ^[0-9]+$ ]]; then
    echo "Error: build number must be a non-negative integer, got '$BUILD'" >&2
    exit 1
fi

# Commit SHA + dirty flag identify the source tree even when a build number
# is reused (--no-bump, branch hopping). Build outputs are excluded from the
# dirty check: Version.h is regenerated here and build.sh rewrites
# BUILD_NUMBER after every bumped build, so neither means "sources changed".
if $IN_GIT; then
    GIT_SHA=$(git rev-parse --short=8 HEAD)
    EXCLUDE=(':!blinky-things/types/Version.h' ':!blinky-things/BUILD_NUMBER')
    if ! git diff --quiet -- . "${EXCLUDE[@]}" \
       || ! git diff --cached --quiet -- . "${EXCLUDE[@]}"; then
        GIT_SHA="${GIT_SHA}-dirty"
    fi
else
    echo "WARNING: not a git checkout; Version.h gets SHA 'nogit'" >&2
    GIT_SHA="nogit"
fi

cat > blinky-things/types/Version.h << EOF
#pragma once

// Generated by scripts/gen_version.sh — do not edit manually.
// See blinky-things/BUILD_NUMBER for the current value.

#define FIRMWARE_BUILD $BUILD
#define FIRMWARE_GIT_SHA "$GIT_SHA"
// FIRMWARE_VERSION embeds both the build number AND the git SHA so a
// reused build number (--no-bump) can't disguise different code on a
// running device.
#define FIRMWARE_VERSION "b$BUILD-$GIT_SHA"
#define FIRMWARE_BUILD_DATE __DATE__ " " __TIME__
EOF

echo "=== Build $BUILD ($GIT_SHA) ==="
