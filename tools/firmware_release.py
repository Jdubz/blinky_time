#!/usr/bin/env python3
"""
firmware_release.py - shared firmware release logic (docs/RELEASE_PROCESS.md).

Used by .github/workflows/release.yml (package), tools/release_gate.py,
tools/release_promote.py, tools/deploy_local.py and scripts/deploy.sh
(download a verified release), so every path agrees on what a release is.

A release is a GitHub Release tagged `b<N>` whose assets are:
  blinky-things-b<N>.hex, blinky-things-b<N>.uf2, manifest.json
plus, once bench-gated, gate-<device_id>.json. Channels:
  candidate  pre-release `b<N>` (CI-built, not yet gated)
  stable     full release `b<N>` + tag `stable-b<N>`; the latest stable is
             the release GitHub marks "Latest" (rollback = re-mark an older one)

CLI:
  firmware_release.py package --hex H --build N --sha SHA --out DIR
  firmware_release.py download [--tag bN] [--out DIR]   (default: latest stable)
  firmware_release.py latest-stable
  firmware_release.py mirror --out DIR [--keep N]   (stable releases for the web flasher)
  firmware_release.py is-test-device <device_id>

Every failure exits non-zero with a message; nothing falls back silently.
"""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TEST_DEVICES = REPO / "devices" / "test_devices.json"
TAG_RE = re.compile(r"^b(\d+)$")


class ReleaseError(Exception):
    pass


# ---------------------------------------------------------------- helpers ---

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def gh(*args, capture=True):
    """Run the GitHub CLI; raise with its stderr on failure."""
    if not shutil.which("gh"):
        raise ReleaseError("GitHub CLI `gh` not found on PATH (needed for releases)")
    r = subprocess.run(["gh", *args], cwd=REPO, capture_output=capture, text=True)
    if r.returncode != 0:
        raise ReleaseError(f"gh {' '.join(args)} failed: {(r.stderr or '').strip()[:500]}")
    return r.stdout if capture else ""


def storage_versions():
    """SETTINGS_VERSION / DEVICE_VERSION from ConfigStorage.h (fail loud if missing)."""
    text = (REPO / "blinky-things/config/ConfigStorage.h").read_text(encoding="utf-8")
    out = {}
    for key in ("SETTINGS_VERSION", "DEVICE_VERSION"):
        m = re.search(rf"\b{key}\s*=\s*(\d+)", text)
        if not m:
            raise ReleaseError(f"{key} not found in ConfigStorage.h")
        out[key.lower()] = int(m.group(1))
    return out


# ------------------------------------------------------------- clean tree ---

# Generated by every build; scripts/gen_version.sh excludes the same files
# from its "-dirty" check, so a tree this function calls clean builds a
# version without "-dirty".
GENERATED = ("blinky-things/types/Version.h", "blinky-things/BUILD_NUMBER")


def dirty_paths():
    """Paths that would make a local build not match its commit: tracked
    changes anywhere (gen_version.sh's rule) plus untracked files under
    blinky-things/ (they compile into the sketch). Fails if git can't tell."""
    r = subprocess.run(["git", "status", "--porcelain", "--untracked-files=all"],
                       cwd=REPO, capture_output=True, text=True)
    if r.returncode != 0:
        raise ReleaseError(f"git status failed: {r.stderr.strip()[:300]}")
    dirty = []
    for line in r.stdout.splitlines():
        status, path = line[:2], line[3:].strip().strip('"')
        if path in GENERATED:
            continue
        if status == "??" and not path.startswith("blinky-things/"):
            continue
        dirty.append(line.strip())
    return dirty


def require_clean_tree(what):
    dirty = dirty_paths()
    if dirty:
        raise ReleaseError(f"{what} needs a clean tree (commit or stash first): " + "; ".join(dirty[:10]))


# ------------------------------------------------------------ test devices ---

def load_test_devices():
    """Device ids allowed to take candidate and --dev builds."""
    if not TEST_DEVICES.exists():
        raise ReleaseError(f"{TEST_DEVICES} missing: no device may take non-stable firmware")
    data = json.loads(TEST_DEVICES.read_text(encoding="utf-8"))
    ids = data.get("test_devices")
    if not isinstance(ids, list) or not all(isinstance(i, str) and i for i in ids):
        raise ReleaseError(f"{TEST_DEVICES}: 'test_devices' must be a list of device ids")
    return set(ids)


def require_test_device(device_id, what):
    if device_id not in load_test_devices():
        raise ReleaseError(f"{what} refused: '{device_id}' is not in {TEST_DEVICES.relative_to(REPO)}. "
                           "Only listed test devices take non-stable firmware.")


# ---------------------------------------------------------------- package ---

def package(hex_path, build, sha, out_dir, toolchain):
    """Validate a compiled hex and write release assets + manifest into out_dir.

    Same validators the deploy paths run (tools/uf2_upload.py), but strict:
    the hex safety check must actually run (uf2_upload.validate_hex skips it
    with a warning when pre_upload_check can't be imported).
    """
    sys.path.insert(0, str(REPO / "tools"))
    import pre_upload_check  # noqa: F401  (must import: no skipped safety check)
    import uf2_upload

    hex_path = Path(hex_path)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    if not uf2_upload.validate_hex(hex_path):
        raise ReleaseError("hex failed safety validation")
    with tempfile.TemporaryDirectory() as tmp:
        uf2_tmp = uf2_upload.convert_to_uf2(hex_path, Path(tmp))
        if not uf2_upload.validate_uf2(uf2_tmp):
            raise ReleaseError("UF2 failed safety validation")
        hex_out = out_dir / f"blinky-things-b{build}.hex"
        uf2_out = out_dir / f"blinky-things-b{build}.uf2"
        shutil.copyfile(hex_path, hex_out)
        shutil.copyfile(uf2_tmp, uf2_out)

    manifest = {
        "build": int(build),
        "version": f"b{build}-{sha[:8]}",
        "git_sha": sha,
        "files": {p.name: sha256(p) for p in (hex_out, uf2_out)},
        "toolchain": toolchain,
        **storage_versions(),
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


# --------------------------------------------------------------- download ---

def list_releases():
    rows = json.loads(gh("release", "list", "--limit", "200",
                         "--json", "tagName,isPrerelease,isLatest,isDraft"))
    return [r for r in rows if TAG_RE.match(r["tagName"]) and not r["isDraft"]]


def repo_slug():
    return json.loads(gh("repo", "view", "--json", "nameWithOwner"))["nameWithOwner"]


def tag_exists(tag):
    """True if refs/tags/<tag> exists on GitHub. Only a 404 means "no"."""
    if not shutil.which("gh"):
        raise ReleaseError("GitHub CLI `gh` not found on PATH (needed for releases)")
    r = subprocess.run(["gh", "api", f"repos/{repo_slug()}/git/ref/tags/{tag}"],
                       cwd=REPO, capture_output=True, text=True)
    if r.returncode == 0:
        return True
    if "404" in (r.stderr or "") or "Not Found" in (r.stderr or ""):
        return False
    raise ReleaseError(f"could not check tag {tag}: {(r.stderr or '').strip()[:300]}")


def release_info(tag):
    return json.loads(gh("release", "view", tag, "--json", "tagName,isPrerelease,isDraft,assets,url"))


def is_stable(tag):
    """Stable = published (not draft), not a pre-release, AND promoted (tag
    stable-b<N> exists). A full release without the promotion marker is not
    stable: release_promote.py is the only way to make one."""
    info = release_info(tag)
    return (not info["isDraft"] and not info["isPrerelease"]
            and tag_exists(f"stable-{tag}"))


def latest_stable_tag():
    latest = [r for r in list_releases() if r["isLatest"]]
    if not latest or not is_stable(latest[0]["tagName"]):
        raise ReleaseError("no stable release yet (the Latest release must be promoted, with tag "
                           "stable-b<N>). Cut a candidate, gate it, and promote it: "
                           "docs/RELEASE_PROCESS.md")
    return latest[0]["tagName"]


def download(tag, out_dir):
    """Download a release's hex/uf2/manifest and verify both firmware files."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    m = TAG_RE.match(tag)
    if not m:
        raise ReleaseError(f"not a release tag: {tag!r} (expected b<N>)")
    n = m.group(1)
    names = ["manifest.json", f"blinky-things-b{n}.hex", f"blinky-things-b{n}.uf2"]
    # Replace only this release's own assets; never touch anything else in out_dir.
    for name in names:
        (out_dir / name).unlink(missing_ok=True)
    gh("release", "download", tag, "--dir", str(out_dir),
       *[a for name in names for a in ("--pattern", name)])
    manifest = json.loads((out_dir / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("build") != int(n):
        raise ReleaseError(f"{tag}: manifest build {manifest.get('build')} != {n}")
    files = manifest.get("files") or {}
    for name in names[1:]:
        p = out_dir / name
        if name not in files:
            raise ReleaseError(f"{tag}: manifest has no sha256 for {name} - refusing to use it")
        if not p.exists():
            raise ReleaseError(f"{tag}: asset {name} missing")
        if sha256(p) != files[name]:
            raise ReleaseError(f"{tag}: {name} sha256 mismatch - refusing to use it")
    return {
        "tag": tag,
        "hex": out_dir / f"blinky-things-b{n}.hex",
        "uf2": out_dir / f"blinky-things-b{n}.uf2",
        "manifest": manifest,
        "stable": is_stable(tag),
    }


# ----------------------------------------------------------------- mirror ---

MIRROR_INDEX_SCHEMA = 1


def mirror_entry(tag, manifest, published_at, url):
    """One index.json entry. Paths are relative to the index (the web flasher
    resolves them against the index URL) and every file carries the sha256 the
    release manifest gave it, so the browser re-verifies what it downloads."""
    n = TAG_RE.match(tag).group(1)
    files = manifest["files"]
    entry = {
        "tag": tag,
        "build": manifest["build"],
        "version": manifest["version"],
        "git_sha": manifest["git_sha"],
        "settings_version": manifest["settings_version"],
        "device_version": manifest["device_version"],
        "published_at": published_at,
        "url": url,
        "files": {},
    }
    for kind in ("hex", "uf2"):
        name = f"blinky-things-b{n}.{kind}"
        entry["files"][kind] = {"path": f"{tag}/{name}", "sha256": files[name]}
    return entry


def mirror(out_dir, keep):
    """Download the newest `keep` stable releases into out_dir/<tag>/ and write
    out_dir/index.json for the web flasher (blinky-console #firmware).

    Only stable releases are mirrored: the web flasher installs firmware on
    devices nobody bench-gated, which is exactly what stable is for. "No
    stable release yet" is written as latest=null, which the flasher shows as
    a refusal; any other failure (download, sha256) aborts the mirror.
    """
    if keep < 1:
        raise ReleaseError(f"--keep must be >= 1, got {keep}")
    out_dir = Path(out_dir)
    if out_dir.exists():
        shutil.rmtree(out_dir)  # never serve a release that is no longer stable
    out_dir.mkdir(parents=True)
    rows = json.loads(gh("release", "list", "--limit", "200",
                         "--json", "tagName,isPrerelease,isLatest,isDraft,publishedAt"))
    rows = [r for r in rows if TAG_RE.match(r["tagName"]) and not r["isDraft"] and not r["isPrerelease"]]
    rows.sort(key=lambda r: int(TAG_RE.match(r["tagName"]).group(1)), reverse=True)
    stable = [r for r in rows if tag_exists(f"stable-{r['tagName']}")]
    latest = [r["tagName"] for r in stable if r["isLatest"]]

    releases = []
    for r in stable[:keep]:
        tag = r["tagName"]
        got = download(tag, out_dir / tag)
        # download() leaves only this release's three assets in the directory.
        releases.append(mirror_entry(tag, got["manifest"], r["publishedAt"], release_info(tag)["url"]))
    if latest and latest[0] not in [e["tag"] for e in releases]:
        raise ReleaseError(f"latest stable {latest[0]} is older than the newest {keep} stable "
                           "releases; raise --keep so the flasher's default is mirrored")
    index = {
        "schema": MIRROR_INDEX_SCHEMA,
        "latest": latest[0] if latest else None,
        "releases": releases,
    }
    (out_dir / "index.json").write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
    return index


# -------------------------------------------------------------------- cli ---

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("package")
    p.add_argument("--hex", required=True)
    p.add_argument("--build", required=True, type=int)
    p.add_argument("--sha", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--toolchain-json", default="{}", help="toolchain versions as JSON")
    d = sub.add_parser("download")
    d.add_argument("--tag", help="b<N> (default: latest stable)")
    d.add_argument("--out", default=str(Path(tempfile.gettempdir()) / "blinky-release"))
    sub.add_parser("latest-stable")
    mi = sub.add_parser("mirror")
    mi.add_argument("--out", required=True, help="directory to (re)create; served as /firmware/")
    mi.add_argument("--keep", type=int, default=5, help="newest stable releases to mirror")
    t = sub.add_parser("is-test-device")
    t.add_argument("device_id")
    sub.add_parser("check-clean")
    args = ap.parse_args()
    try:
        if args.cmd == "package":
            m = package(args.hex, args.build, args.sha, args.out, json.loads(args.toolchain_json))
            print(json.dumps(m, indent=2))
        elif args.cmd == "download":
            r = download(args.tag or latest_stable_tag(), args.out)
            print(json.dumps({"tag": r["tag"], "stable": r["stable"], "hex": str(r["hex"]),
                              "uf2": str(r["uf2"]), "version": r["manifest"]["version"]}))
        elif args.cmd == "latest-stable":
            print(latest_stable_tag())
        elif args.cmd == "mirror":
            index = mirror(args.out, args.keep)
            if index["latest"] is None:
                print("WARNING: no stable release yet; the web flasher will refuse to flash",
                      file=sys.stderr)
            print(json.dumps({"latest": index["latest"],
                              "mirrored": [e["tag"] for e in index["releases"]]}))
        elif args.cmd == "is-test-device":
            require_test_device(args.device_id, "check")
            print("yes")
        elif args.cmd == "check-clean":
            require_clean_tree("--dev build")
            print("clean")
    except ReleaseError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
